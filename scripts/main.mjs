import {persistItemMigrations} from './item-migration.mjs?v=0.3.15';
Hooks.once('ready',()=>persistItemMigrations().catch(error=>{console.error(error);ui.notifications.error('Item migration could not be saved: '+error.message);}));
import {registerCloneSocket} from './clones.mjs?v=0.3.15';
Hooks.once('ready',registerCloneSocket);
import {registerDamageSocket,addDamageControls} from './damage.mjs?v=0.3.15';
Hooks.once('ready',registerDamageSocket);
Hooks.on('renderChatMessageHTML',addDamageControls);
import { SYSTEM_ID, ITEM_TYPES, RECORD_TYPES } from "./config.mjs?v=0.3.15";
import { EocActorModel, EocItemModel, EocRecordModel, EocTraitModel, EocProfessionModel, EocJutsuModel, EocHeritageModel } from "./models.mjs?v=0.3.15";
import { EocActorSheet, EocNpcSheet, EocItemSheet } from "./sheets.mjs?v=0.3.15";
import { registerMultiTargetExplosions } from "./dice.mjs?v=0.3.15";
import { EocActor, EocItem, EocActiveEffect } from "./documents.mjs?v=0.3.15";
import { addCompendiumBrowser } from "./library.mjs?v=0.3.15";
import { decorateChatMessage } from "./chat.mjs?v=0.3.15";
import {initializePools,addPoolButton,refreshPools} from './pool-window.mjs?v=0.3.15';
import {registerRerollSocket,addRerollControl} from './rerolls.mjs?v=0.3.15';
import {addChatActions} from './chat-actions.mjs?v=0.3.15';
import {onProfessionCreated} from './profession-equipment.mjs?v=0.3.15';
import {addImportButton} from './importer.mjs?v=0.3.15';
import {configureInitiative} from './initiative.mjs?v=0.3.15';
Hooks.on('renderActorDirectory',(app,html)=>addImportButton('npc',app,html));
Hooks.on('renderItemDirectory',(app,html)=>addImportButton('item',app,html));
Hooks.on('createItem',onProfessionCreated);
Hooks.on('renderChatMessageHTML',addChatActions);
import {addEffectKeyDropdowns} from './effect-keys.mjs?v=0.3.15';
Hooks.once('ready',()=>{initializePools();registerRerollSocket();});
Hooks.on('renderActiveEffectConfig',addEffectKeyDropdowns);
Hooks.on('renderChatMessageHTML',addRerollControl);
Hooks.on('renderChatLog',addPoolButton);
Hooks.on('updateSetting',refreshPools);
Hooks.on("renderCompendiumDirectory",addCompendiumBrowser);
Hooks.on("renderChatMessageHTML",decorateChatMessage);
Hooks.once("init", () => {
  configureInitiative();
  CONFIG.Actor.documentClass = EocActor;
  CONFIG.Item.documentClass = EocItem;
  CONFIG.ActiveEffect.documentClass = EocActiveEffect;
  registerMultiTargetExplosions(foundry.dice.terms.Die);
  CONFIG.Actor.dataModels.character = EocActorModel;
  CONFIG.Actor.dataModels.npc = EocActorModel;
  for (const type of ITEM_TYPES) CONFIG.Item.dataModels[type] = RECORD_TYPES.includes(type) ? EocRecordModel : EocItemModel;
  CONFIG.Item.dataModels.trait = EocTraitModel;
  CONFIG.Item.dataModels.profession = EocProfessionModel;
  for(const type of ["technique"])CONFIG.Item.dataModels[type] = EocJutsuModel;
  CONFIG.Item.dataModels.heritage = EocHeritageModel;
  game.settings.register(SYSTEM_ID, "misfortune", { name: "Misfortune Points", hint: "Shared GM pool used to trigger Antagonist Traits.", scope: "world", config: true, type: Number, default: 0, range: { min: 0, max: 100, step: 1 } });
  game.settings.register(SYSTEM_ID, 'fortune', {name:'Fortune Points',scope:'world',config:true,type:Number,default:0,range:{min:0,max:100,step:1}});
  foundry.applications.apps.DocumentSheetConfig.registerSheet(Actor, SYSTEM_ID, EocActorSheet, { types: ["character"], makeDefault: true, label: "EOC.ActorSheet" });
  foundry.applications.apps.DocumentSheetConfig.registerSheet(Actor, SYSTEM_ID, EocNpcSheet, {types:['npc'],makeDefault:true,label:'EoC Antagonist / NPC Sheet'});
  foundry.applications.apps.DocumentSheetConfig.registerSheet(Item, SYSTEM_ID, EocItemSheet, { types: ITEM_TYPES, makeDefault: true, label: "EOC.ItemSheet" });
});
